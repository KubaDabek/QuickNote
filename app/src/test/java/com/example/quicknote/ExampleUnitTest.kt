package com.example.quicknote

import org.junit.Test
import org.junit.Assert.*

/**
 * Przykładowy test jednostkowy (unit test), który wykonuje się na maszynie deweloperskiej (host).
 * Testy tego typu nie wymagają urządzenia ani emulatora Androida.
 */
class ExampleUnitTest {
    /**
     * Test sprawdza, czy podstawowa operacja dodawania działa poprawnie.
     */
    @Test
    fun addition_isCorrect() {
        assertEquals(4, 2 + 2)
    }
}
